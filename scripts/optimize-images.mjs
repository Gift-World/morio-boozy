// Image pipeline: makes responsive WebP versions of every image the site
// references and writes a typed manifest (src/lib/images.gen.ts).
//
//   npm run images            # only (re)builds what's missing or changed
//
// Originals in public/assets/images stay untouched (they're the source of
// truth and keep old URLs such as the og:image working). Variants go to
// public/assets/images/opt/ with a content hash, so they can be cached forever.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pub = path.join(root, "public");
const outDir = path.join(pub, "assets/images/opt");
const WIDTHS = [160, 320, 480, 640, 960, 1280, 1920];
const QUALITY = 80;

// 1. find referenced images in the app sources
const sources = [];
const walk = (d) => {
  for (const f of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, f.name);
    if (f.isDirectory()) walk(p);
    else if (/\.(tsx?|css)$/.test(f.name) && !f.name.endsWith(".gen.ts")) sources.push(p);
  }
};
walk(path.join(root, "src"));
const refs = new Set();
for (const f of sources) {
  for (const m of fs.readFileSync(f, "utf8").matchAll(/\/assets\/images\/[\w./-]+\.(?:jpe?g|png|webp)/gi)) {
    if (!m[0].includes("/opt/") && fs.existsSync(path.join(pub, m[0]))) refs.add(m[0]);
  }
}

// 2. build variants
fs.mkdirSync(outDir, { recursive: true });
const manifest = {};
let made = 0;
for (const ref of [...refs].sort()) {
  const file = path.join(pub, ref);
  const buf = fs.readFileSync(file);
  const hash = crypto.createHash("sha1").update(buf).update(String(QUALITY)).digest("hex").slice(0, 8);
  const meta = await sharp(buf).metadata();
  const width = meta.width;
  const height = meta.height;
  const alpha = meta.hasAlpha;
  // short names: Windows checkouts in deep folders hit the 260-char path limit
  const base = path.basename(ref).replace(/\.[^.]+$/, "").replace(/[^\w-]/g, "-").slice(0, 20);
  const widths = WIDTHS.filter((w) => w < width);
  widths.push(Math.min(width, 2400));
  const variants = [];
  for (const w of [...new Set(widths)]) {
    const name = `${base}-${w}.${hash}.webp`;
    const out = path.join(outDir, name);
    if (!fs.existsSync(out)) {
      await sharp(buf).resize({ width: w, withoutEnlargement: true }).webp({ quality: QUALITY, alphaQuality: 90, effort: 5, smartSubsample: true }).toFile(out);
      made++;
    }
    variants.push([w, `/assets/images/opt/${name}`]);
  }
  manifest[ref] = { width, height, alpha, variants };
}

// 3. drop stale files
const keep = new Set(Object.values(manifest).flatMap((m) => m.variants.map(([, u]) => path.basename(u))));
for (const f of fs.readdirSync(outDir)) if (!keep.has(f)) fs.rmSync(path.join(outDir, f));

fs.writeFileSync(
  path.join(root, "src/lib/images.gen.ts"),
  `// Generated by scripts/optimize-images.mjs — do not edit.\n` +
    `export interface ImageInfo {\n  width: number;\n  height: number;\n  alpha: boolean;\n  /** [width, url] pairs, ascending */\n  variants: [number, string][];\n}\n\n` +
    `export const images: Record<string, ImageInfo> = ${JSON.stringify(manifest, null, 2)};\n`,
);
const total = (dir) => fs.readdirSync(dir).reduce((t, f) => t + fs.statSync(path.join(dir, f)).size, 0);
console.log(`${refs.size} images, ${made} new variants, opt/ = ${(total(outDir) / 1048576).toFixed(1)} MB`);
