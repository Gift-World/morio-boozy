import type { ImgHTMLAttributes } from "react";
import { images } from "../lib/images.gen";

type Props = Omit<ImgHTMLAttributes<HTMLImageElement>, "src" | "srcSet" | "width" | "height"> & {
  /** Original path under /assets/images (see scripts/optimize-images.mjs). */
  src: string;
  alt: string;
  /**
   * How wide the image renders, e.g. "(min-width: 992px) 25vw, 100vw".
   * Use "intrinsic" for images the CSS doesn't size (logos, icons): they get
   * a single WebP at the original pixel size, since a srcset would change
   * their natural size.
   */
  sizes: string;
  /** Above-the-fold image: load eagerly with high priority. */
  priority?: boolean;
};

/**
 * Responsive image: serves the WebP variants generated by the image pipeline
 * with srcset/sizes, intrinsic width/height (no layout shift) and lazy
 * loading unless `priority` is set. Falls back to the original file if the
 * image hasn't been through the pipeline yet.
 */
export function Photo({ src, alt, sizes, priority = false, ...rest }: Props) {
  const info = images[src];
  if (!info) return <img src={src} alt={alt} loading={priority ? undefined : "lazy"} decoding="async" {...rest} />;
  const intrinsic = sizes === "intrinsic";
  const fallback = intrinsic
    ? info.variants[info.variants.length - 1]
    : (info.variants.find(([w]) => w >= 960) ?? info.variants[info.variants.length - 1]);
  return (
    <img
      src={fallback[1]}
      srcSet={intrinsic ? undefined : info.variants.map(([w, url]) => `${url} ${w}w`).join(", ")}
      sizes={intrinsic ? undefined : sizes}
      width={info.width}
      height={info.height}
      alt={alt}
      loading={priority ? "eager" : "lazy"}
      fetchPriority={priority ? "high" : undefined}
      decoding="async"
      {...rest}
    />
  );
}

/** Variant URL at least `width` pixels wide (or the largest available). */
export function variantUrl(src: string, width: number) {
  const info = images[src];
  if (!info) return src;
  return (info.variants.find(([w]) => w >= width) ?? info.variants[info.variants.length - 1])[1];
}

/**
 * CSS custom properties for a responsive full-width background. Paired with
 * the `--bg-*` rules in styles/enhancements.css (phone / tablet / desktop).
 */
export function bgVars(src: string): Record<string, string> {
  return {
    "--bg-sm": `url('${variantUrl(src, 960)}')`,
    "--bg-md": `url('${variantUrl(src, 1280)}')`,
    "--bg-lg": `url('${variantUrl(src, 1920)}')`,
  };
}
